export const dictionaries = { zh, en };
export const LANGS = ['zh', 'en'];

const storage = typeof localStorage === 'undefined' ? null : localStorage;
const browserLang = typeof navigator === 'undefined' ? 'en' : navigator.language || 'en';

export function detectLang() {
  const saved = storage && storage.getItem('flybody.lang');
  if (LANGS.includes(saved)) return saved;
  return browserLang.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

let lang = detectLang();

export const getLang = () => lang;

export function setLang(next) {
  if (!LANGS.includes(next)) return lang;
  lang = next;
  if (storage) storage.setItem('flybody.lang', lang);
  if (typeof document !== 'undefined') document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
  return lang;
}

/** `t('key', {name: 'x'})`, falling back to zh then to the key itself. */
export function t(key, vars) {
  const text = dictionaries[lang][key] ?? dictionaries.zh[key] ?? key;
  return vars ? text.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? vars[name] : match)) : text;
}

export const fmtNum = (value) => new Intl.NumberFormat(lang === 'zh' ? 'zh-CN' : 'en-US').format(value);

/** Rewrites every `[data-i18n]` text node and `[data-i18n-attr]` attribute pair. */
export function applyStatic(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-attr]')) {
    for (const pair of el.dataset.i18nAttr.split(',')) {
      const [attr, key] = pair.split(':');
      if (attr && key) el.setAttribute(attr.trim(), t(key.trim()));
    }
  }
}
